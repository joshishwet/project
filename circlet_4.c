#include <stdio.h>
int main() 
{
    int a, b;

    for (a = 1; a <= 5; a++) {
        for (b = 1; b < a; b++)
        {
            printf("  ");
        }

        for (b = 1; b <= 5 - a + 1; b++)
        {
            printf("%d ", ((a + b) % 2));
        }
        printf("\n");
    }
}
