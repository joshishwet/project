#include <stdio.h>

    int main() 
{
    int x, y, sp;

    for (x = 1; x <= 5; x++)
	 {
        for (y = 1; y <= x; y++) {
            printf("%d ", y);
        }
        sp = 2 * (5 - x);
        for (y = 1; y <= sp; y++) {
            printf("  ");
        }

        for (y = x; y >= 1; y--) 
        {
            printf("%d ", y);
        }

        printf("\n");
    }
}

